-- 食物库：浏览次数。
--   用途——详情页每被查看一次 +1；食物库列表按此**降序**（常用食物自动上浮，同值按名称），
--   等价于一份「个人常用度」的隐式排序。
--   说明——预置数据（user_id NULL）为全系统共享，其浏览计数也是**全局共享**（自用工具可接受）；
--          用户自建各自独立。计数只增不减，删除食物时随行一起消失。
ALTER TABLE `food`
    ADD COLUMN `view_count` INT NOT NULL DEFAULT 0
        COMMENT '浏览次数（详情页查看次数；列表按其降序，同值按名称）' AFTER `category`;
